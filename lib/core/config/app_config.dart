import 'package:flutter/foundation.dart';
import 'package:eyadty/core/storage/cache_helper.dart';

/// Selects whether the app talks to the in-process local server simulation
/// (`local`, default) or the real HTTP backend (`remote`) at [AppConfig.baseUrl].
///
/// Distinct from [DataMode.forcedLocal], which is a user-facing sync pause
/// ("do not sync now") while still configured for a backend.
enum BackendMode { local, remote }

/// Central application configuration for Eyadty.
///
/// Supports compile-time configuration via `--dart-define`:
/// - `BACKEND_MODE`: `local` (default) or `remote`.
/// - `DEMO_MODE`: legacy boolean flag (defaults to `true`); setting `false`
///   without `BACKEND_MODE=local` also selects `remote`.
/// - `BASE_URL`: string URL for the backend API (defaults to `http://192.168.1.60:1601/`).
class AppConfig {
  AppConfig._();

  static const String _runtimeBackendModeKey = 'qa_backend_mode';

  // ─── Environment Defines ──────────────────────────────────────────────────
  static const String _defaultBackendMode = String.fromEnvironment(
    'BACKEND_MODE',
    defaultValue: 'local',
  );

  static const bool _defaultDemoMode = bool.fromEnvironment(
    'DEMO_MODE',
    defaultValue: true,
  );

  static const String _rawBaseUrl = String.fromEnvironment(
    'BASE_URL',
    defaultValue: 'http://192.168.1.60:1601/',
  );

  // ─── Runtime & Testing Overrides ──────────────────────────────────────────
  static BackendMode? _runtimeBackendMode;
  static BackendMode? _backendModeOverride;
  static bool? _demoModeOverride;
  static String? _baseUrlOverride;

  /// Active backend mode (`local` or `remote`).
  static BackendMode get backendMode {
    if (_backendModeOverride != null) return _backendModeOverride!;
    if (_runtimeBackendMode != null) return _runtimeBackendMode!;
    if (_defaultBackendMode.toLowerCase() == 'remote' || !_defaultDemoMode) {
      return BackendMode.remote;
    }
    return BackendMode.local;
  }

  /// Whether the app is using the in-process local server simulation.
  static bool get isLocalMode => backendMode == BackendMode.local;

  /// Whether the app is configured to talk to the remote HTTP server.
  static bool get isRemoteMode => backendMode == BackendMode.remote;

  /// Whether demo login & local-mode indicators are enabled.
  static bool get isDemoMode => _demoModeOverride ?? isLocalMode;

  /// Persists and applies a runtime backend mode switch (QA settings).
  static Future<void> setRuntimeBackendMode(BackendMode mode) async {
    _runtimeBackendMode = mode;
    _backendModeOverride = null;
    _demoModeOverride = null;
    try {
      await AppSharedPreferences.setString(
        value: mode.name,
        key: _runtimeBackendModeKey,
      );
    } catch (_) {
      // SharedPreferences may not be initialized in unit tests.
    }
  }

  /// Restores runtime backend mode from [AppSharedPreferences] if saved.
  static void loadRuntimeBackendMode() {
    try {
      final saved = AppSharedPreferences.getString(key: _runtimeBackendModeKey);
      if (saved == BackendMode.remote.name) {
        _runtimeBackendMode = BackendMode.remote;
      } else if (saved == BackendMode.local.name) {
        _runtimeBackendMode = BackendMode.local;
      }
    } catch (_) {}
  }

  /// The normalized backend base URL (always ending with a trailing slash).
  static String get baseUrl {
    final raw = _baseUrlOverride ?? _rawBaseUrl;
    return raw.endsWith('/') ? raw : '$raw/';
  }

  /// Normalized API v1 endpoint URL.
  static String get apiUrl => '${baseUrl}api/v1/';

  /// Base uploads URL for assets/images.
  static String get baseImageUrl => '${baseUrl}uploads';

  // ─── Local / Demo Session Tokens ──────────────────────────────────────────
  static const String demoTokenPrefix = 'eyadty_demo_session_';

  /// Generates a structured local session token tagged with [demoTokenPrefix].
  static String generateDemoToken(String userId) {
    final timestamp = DateTime.now().millisecondsSinceEpoch;
    return '$demoTokenPrefix${userId}_$timestamp';
  }

  /// Checks if a given token was generated by the local login system.
  static bool isDemoToken(String token) {
    return token.startsWith(demoTokenPrefix) ||
        token.startsWith('eyadty_session_');
  }

  // ─── Test Helpers ─────────────────────────────────────────────────────────
  @visibleForTesting
  static void setBackendModeForTesting(BackendMode? mode) {
    _backendModeOverride = mode;
    if (mode != null) {
      _demoModeOverride = mode == BackendMode.local;
    } else {
      _demoModeOverride = null;
    }
  }

  @visibleForTesting
  static void setDemoModeForTesting(bool? value) {
    _demoModeOverride = value;
    _backendModeOverride =
        value == null ? null : (value ? BackendMode.local : BackendMode.remote);
  }

  @visibleForTesting
  static void setBaseUrlForTesting(String? value) {
    _baseUrlOverride = value;
  }

  @visibleForTesting
  static void resetTestingOverrides() {
    _runtimeBackendMode = null;
    _backendModeOverride = null;
    _demoModeOverride = null;
    _baseUrlOverride = null;
  }
}
